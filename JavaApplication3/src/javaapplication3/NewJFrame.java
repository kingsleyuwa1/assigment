    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        String name = jTextField1.getText().trim();
    String surname = jTextField2.getText().trim();
    String id = jTextField3.getText().trim();
    String dob = jTextField4.getText().trim();
    String gender = jComboBox1.getSelectedItem().toString();
    String contact = jTextField5.getText().trim();
    String email = jTextField6.getText().trim();

    // 1. Empty field check
    if (name.isEmpty() || surname.isEmpty() || id.isEmpty() || dob.isEmpty()
            || contact.isEmpty() || email.isEmpty()) {
        JOptionPane.showMessageDialog(this, "All fields are required.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 2. Name/Surname: letters only
    if (!name.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(this, "Name must contain letters only.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (!surname.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(this, "Surname must contain letters only.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 3. ID: numeric only (adjust length as needed, e.g. 13 digits)
    if (!id.matches("\\d+")) {
        JOptionPane.showMessageDialog(this, "ID must contain numbers only.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 4. Date of Birth: format check (dd/MM/yyyy)
    if (!dob.matches("\\d{2}/\\d{2}/\\d{4}")) {
        JOptionPane.showMessageDialog(this, "Date of Birth must be in dd/MM/yyyy format.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 5. Contact number: digits only, e.g. 10 digits
    if (!contact.matches("\\d{10}")) {
        JOptionPane.showMessageDialog(this, "Contact number must be exactly 10 digits.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 6. Email format check
    if (!email.matches("^[\\w.+-]+@[\\w-]+\\.[a-zA-Z]{2,}$")) {
        JOptionPane.showMessageDialog(this, "Please enter a valid email address.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // All validations passed
    JOptionPane.showMessageDialog(this, "Login successful!", "Success", JOptionPane.INFORMATION_MESSAGE);
        
    }//GEN-LAST:event_jButton1ActionPerformed

